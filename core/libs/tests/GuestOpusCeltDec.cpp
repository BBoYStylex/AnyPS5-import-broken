void Require(bool value) { if (!value) std::abort(); }

template <typename TFunction>
void RequireThrows(TFunction function) {
    try { function(); } catch (const std::runtime_error&) { return; }
    std::abort();
}

int Peak(const std::int16_t* start, std::size_t count) {
    int peak = 0;
    for (std::size_t i = 0; i < count; ++i) peak = std::max(peak, std::abs(static_cast<int>(start[i])));
    return peak;
}

